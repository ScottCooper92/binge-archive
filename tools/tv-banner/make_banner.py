"""Writes app/src/main/res/drawable/tv_banner.xml: the launcher mark in a tile, and the app's name beside it.

A vector drawable cannot draw text, so the name is outlined from Outfit, the typeface the design system's
UI uses (design-system/designsystem/src/main/res/font/outfit.ttf, SIL OFL 1.1, licence in the design
system's assets/fonts/Outfit-OFL.txt), at weight 700. Kerning is not applied; the two lines are short.

Run: python3 tools/tv-banner/make_banner.py  (needs fonttools). Edit the BRAND block to make another app's.
"""

import os
import sys

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
FONT = os.path.join(REPO, "design-system/designsystem/src/main/res/font/outfit.ttf")
OUT = os.path.join(REPO, "app/src/main/res/drawable/tv_banner.xml")

BRAND = {
    "line1": "Archive",
    "line2": "Binge",
    "name_colour": "#34D399",
    "sub_colour": "#9FD9C3",
    "backdrop": ("#FF0E1A16", "#FF060C0A"),
    "tile": ("#FF1F4237", "#FF16302A", "#FF0F1F1A"),
    "arc": ("#FF6EE7B7", "#FF059669"),
    "disc": "#34D399",
    "bloom": "#1434D399",
}

TILE = (28, 40, 128, 140)
TILE_R = 22
TEXT_LEFT, TEXT_RIGHT = 152, 288
LINE1_MAX_PX, LINE2_MAX_FRAC = 56, 0.5
GAP = 8


def outline(font, text, size, x, baseline):
    """Path data for [text] at [size] px (em), left edge [x], baseline y; returns (path, width)."""
    glyphs = font.getGlyphSet()
    cmap = font.getBestCmap()
    scale = size / font["head"].unitsPerEm
    pen_x = 0.0
    parts = []
    for ch in text:
        name = cmap[ord(ch)]
        pen = SVGPathPen(glyphs, ntos=lambda v: ("%.2f" % v).rstrip("0").rstrip("."))
        glyphs[name].draw(TransformPen(pen, (scale, 0, 0, -scale, x + pen_x * scale, baseline)))
        parts.append(pen.getCommands())
        pen_x += glyphs[name].width
    return "".join(parts), pen_x * scale


def fit(font, text, max_width, max_size):
    """The largest size up to [max_size] at which [text] is no wider than [max_width]."""
    _, width = outline(font, text, 100, 0, 0)
    return min(max_size, 100 * max_width / width)


def cap_height(font, size):
    return font["OS/2"].sCapHeight * size / font["head"].unitsPerEm


def main():
    font = instantiateVariableFont(TTFont(FONT), {"wght": 700})
    width = TEXT_RIGHT - TEXT_LEFT
    s1 = fit(font, BRAND["line1"], width, LINE1_MAX_PX)
    s2 = min(fit(font, BRAND["line2"], width, 100), s1 * LINE2_MAX_FRAC)
    h1, h2 = cap_height(font, s1), cap_height(font, s2)
    block = h1 + GAP + h2
    top = 90 - block / 2
    base2 = top + h2
    base1 = base2 + GAP + h1
    p1, _ = outline(font, BRAND["line1"], s1, TEXT_LEFT, base1)
    p2, _ = outline(font, BRAND["line2"], s2, TEXT_LEFT, base2)
    l, t, r, b = TILE
    tile = f"M{l + TILE_R},{t}H{r - TILE_R}A{TILE_R},{TILE_R} 0 0 1 {r},{t + TILE_R}V{b - TILE_R}A{TILE_R},{TILE_R} 0 0 1 {r - TILE_R},{b}H{l + TILE_R}A{TILE_R},{TILE_R} 0 0 1 {l},{b - TILE_R}V{t + TILE_R}A{TILE_R},{TILE_R} 0 0 1 {l + TILE_R},{t}Z"
    bk0, bk1 = BRAND["backdrop"]
    t0, t1, t2 = BRAND["tile"]
    a0, a1 = BRAND["arc"]
    xml = f"""<?xml version="1.0" encoding="utf-8"?>
<!--
    The Android TV home-screen banner, 320x180 at xhdpi as the platform asks for, in the host's layout: the
    launcher mark in a rounded tile on the left, the app's name beside it. Generated by
    tools/tv-banner/make_banner.py; edit that, not the numbers here.

    The name is in the banner because the TV quality checklist asks for one that identifies the app. It is
    not localised: it is a proper noun, so one banner serves every locale. A vector cannot draw text, so the
    glyphs are outlined from Outfit, the UI's typeface (SIL OFL 1.1).
-->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="320dp"
    android:height="180dp"
    android:viewportWidth="320"
    android:viewportHeight="180">
    <path android:pathData="M0,0h320v180h-320z">
        <aapt:attr name="android:fillColor">
            <gradient
                android:type="radial"
                android:centerX="90"
                android:centerY="40"
                android:gradientRadius="260">
                <item android:offset="0.0" android:color="{bk0}"/>
                <item android:offset="1.0" android:color="{bk1}"/>
            </gradient>
        </aapt:attr>
    </path>
    <path android:pathData="{tile}">
        <aapt:attr name="android:fillColor">
            <gradient
                android:type="radial"
                android:centerX="{l + 30}"
                android:centerY="{t + 24}"
                android:gradientRadius="113">
                <item android:offset="0.0" android:color="{t0}"/>
                <item android:offset="0.6" android:color="{t1}"/>
                <item android:offset="1.0" android:color="{t2}"/>
            </gradient>
        </aapt:attr>
    </path>
    <group>
        <clip-path android:pathData="{tile}"/>
        <path
            android:fillColor="{BRAND["bloom"]}"
            android:pathData="M172,140 A44,44 0 1 1 84,140 A44,44 0 1 1 172,140 Z"/>
    </group>
    <group
        android:scaleX="0.95"
        android:scaleY="0.95"
        android:translateX="26.7"
        android:translateY="38.7">
        <path
            android:pathData="M54,22 A32,32 0 1,0 54,86 A32,32 0 1,0 54,22 Z"
            android:strokeColor="{BRAND["disc"]}"
            android:strokeAlpha="0.16"
            android:strokeWidth="6"/>
        <path
            android:pathData="M54,22 A32,32 0 1,1 54,86 A32,32 0 1,1 54,22 Z"
            android:strokeWidth="6"
            android:strokeLineCap="round"
            android:trimPathStart="0"
            android:trimPathEnd="0.84">
            <aapt:attr name="android:strokeColor">
                <gradient
                    android:type="linear"
                    android:startX="54"
                    android:startY="22"
                    android:endX="54"
                    android:endY="86">
                    <item android:offset="0.0" android:color="{a0}"/>
                    <item android:offset="1.0" android:color="{a1}"/>
                </gradient>
            </aapt:attr>
        </path>
        <group
            android:pivotX="54"
            android:pivotY="54"
            android:scaleX="0.6"
            android:scaleY="0.6">
            <path
                android:fillColor="{BRAND["disc"]}"
                android:fillType="evenOdd"
                android:pathData="M34,36 h40 a4,4 0 0,1 4,4 v28 a4,4 0 0,1 -4,4 h-40 a4,4 0 0,1 -4,-4 v-28 a4,4 0 0,1 4,-4 z M36,40 v4 h4 v-4 z M36,48 v4 h4 v-4 z M36,56 v4 h4 v-4 z M36,64 v4 h4 v-4 z M68,40 v4 h4 v-4 z M68,48 v4 h4 v-4 z M68,56 v4 h4 v-4 z M68,64 v4 h4 v-4 z M49,46 L61,54 L49,62 Z"/>
        </group>
    </group>
    <path
        android:fillColor="{BRAND["name_colour"]}"
        android:pathData="{p1}"/>
    <path
        android:fillColor="{BRAND["sub_colour"]}"
        android:pathData="{p2}"/>
</vector>
"""
    with open(OUT, "w") as f:
        f.write(xml)
    print("wrote", OUT, "line1 %.1fpx line2 %.1fpx" % (s1, s2), file=sys.stderr)



if __name__ == "__main__":
    main()
